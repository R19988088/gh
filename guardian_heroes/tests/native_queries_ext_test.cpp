uint64_t Dirty(uint32_t low, unsigned seed) {
  constexpr uint32_t high[] = {0, 0xFFFFFFFFu, 0x80000000u, 0x5A59A5A6u};
  return (uint64_t(high[seed % 4]) << 32) | low;
}

